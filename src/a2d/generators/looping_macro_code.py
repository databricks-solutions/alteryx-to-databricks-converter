"""PySpark for a batch or iterative macro call (:class:`LoopingMacroNode`).

The macro's steps become a function, generated by the same per-step code as the
rest of the notebook; the call becomes a loop around it:

* batch: one run per record of the Control input (values from that record are
  the function's parameters; with a group-by, each run gets only the matching
  input rows), and each output is the union of the runs;
* iterative: the function runs on the input, the iteration output is fed back
  in until it's empty or the iteration limit is hit, and each other output is
  the union of the iterations.

Control values were written into the macro's settings as placeholders (see
:mod:`a2d.macro.looping`); here every string literal holding one becomes an
expression with the function's parameter in its place, found with
:mod:`tokenize` so nothing else in the code is touched. A placeholder that
can't be replaced that way stays a TODO.
"""

from __future__ import annotations

import ast
import io
import re
import tokenize
from typing import TYPE_CHECKING

from a2d.generators.base import NodeCodeResult
from a2d.ir.nodes import CommentNode, LoopingMacroNode, MacroIONode
from a2d.macro.looping import ITERATION_SENTINEL, SENTINEL_RE

if TYPE_CHECKING:
    from a2d.generators.pyspark import PySparkGenerator

_BAND = 1_000_000  # macro tool ids are banded; tool N of the macro is band + N
_ITERATION_VAR = "iteration"
# Any placeholder, as one group (re.split keeps it): a control value or the iteration number.
_PLACEHOLDER_RE = re.compile(r"(zza2dparam\d+zz|" + ITERATION_SENTINEL + ")", re.IGNORECASE)


def _slug(text: str) -> str:
    return re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_").lower() or "out"


def output_vars(node: LoopingMacroNode) -> dict[str, str]:
    """The variable each of the call's output anchors is assigned to."""
    if len(node.outputs) == 1:
        return {node.outputs[0][0]: f"df_{node.node_id}"}
    return {name: f"df_{node.node_id}_{_slug(name)}" for name, _ in node.outputs}


# ── turning placeholders back into parameters ──────────────────────────────


def _offsets(source: str) -> list[int]:
    starts, pos = [0], 0
    for line in source.splitlines(keepends=True):
        pos += len(line)
        starts.append(pos)
    return starts


def substitute(
    source: str, params: dict[int, str], iteration: str | None, suffixes: dict[int, str] | None = None
) -> tuple[str, list[str]]:
    """Replace placeholders in ``source`` with the parameters they stand for.

    ``params`` maps placeholder number -> parameter name; ``suffixes`` the text
    written after a placeholder that its value replaces too (a file extension).
    Returns the new source and the placeholders that couldn't be replaced.
    """
    suffixes = suffixes or {}
    edits: list[tuple[tuple[int, int], tuple[int, int], str]] = []
    left: list[str] = []
    prev_type = None
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
    except (tokenize.TokenError, SyntaxError):
        if _PLACEHOLDER_RE.search(source):
            return source, ["the macro's code isn't valid Python, so its parameters couldn't be wired in"]
        return source, []

    def expr_for(match: str) -> str | None:
        if match == ITERATION_SENTINEL:
            return f"str({iteration})" if iteration else None
        found = SENTINEL_RE.fullmatch(match)
        return params.get(int(found.group(1))) if found else None

    for tok in tokens:
        text = tok.string
        if tok.type == tokenize.STRING and _PLACEHOLDER_RE.search(text):
            try:
                value = ast.literal_eval(text)
            except (ValueError, SyntaxError):
                value = None
            # A literal right after another literal is implicit concatenation:
            # an expression there would turn into a call, so leave it.
            if not isinstance(value, str) or prev_type == tokenize.STRING:
                left.append(text)
            else:
                parts: list[str] = []
                ok = True
                strip = ""
                for piece in _PLACEHOLDER_RE.split(value):
                    if strip and piece.startswith(strip):
                        piece = piece[len(strip) :]
                    strip = ""
                    if not piece:
                        continue
                    if _PLACEHOLDER_RE.fullmatch(piece):
                        expr = expr_for(piece)
                        if expr is None:
                            ok = False
                            break
                        parts.append(expr)
                        found = SENTINEL_RE.fullmatch(piece)
                        strip = suffixes.get(int(found.group(1)), "") if found else ""
                    else:
                        parts.append(repr(piece))
                if ok:
                    edits.append((tok.start, tok.end, parts[0] if len(parts) == 1 else "(" + " + ".join(parts) + ")"))
                else:
                    left.append(text)
        elif tok.type == tokenize.NUMBER and text == ITERATION_SENTINEL and iteration:
            # A number in the code is a Spark value there (a formula, a filter).
            edits.append((tok.start, tok.end, f"F.lit({iteration})"))
        elif tok.type == tokenize.COMMENT and _PLACEHOLDER_RE.search(text):
            readable = _PLACEHOLDER_RE.sub(lambda m: expr_for(m.group(0)) or m.group(0), text)
            edits.append((tok.start, tok.end, readable))
        elif _PLACEHOLDER_RE.search(text):
            left.append(text)
        if tok.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.COMMENT, tokenize.INDENT, tokenize.DEDENT):
            prev_type = tok.type

    starts = _offsets(source)
    out = source
    for (srow, scol), (erow, ecol), new in sorted(edits, reverse=True):
        a, b = starts[srow - 1] + scol, starts[erow - 1] + ecol
        out = out[:a] + new + out[b:]
    return out, left


def _indent(source: str) -> str:
    """Indent ``source`` one level, leaving the inside of multi-line strings alone."""
    keep: set[int] = set()  # 0-based lines that continue a multi-line string
    try:
        for tok in tokenize.generate_tokens(io.StringIO(source).readline):
            if tok.type == tokenize.STRING and tok.end[0] > tok.start[0]:
                keep.update(range(tok.start[0], tok.end[0]))
    except (tokenize.TokenError, SyntaxError):
        pass
    return "\n".join(line if (i in keep or not line) else f"    {line}" for i, line in enumerate(source.split("\n")))


# ── the function and the loop ──────────────────────────────────────────────


def _body(gen: PySparkGenerator, node: LoopingMacroNode) -> tuple[list[str], set[str], list[str], dict[str, str]]:
    """The macro's steps, the imports and warnings they need, and the variable
    holding each output."""
    body = node.body
    var_map: dict[int, dict[str, str]] = {}
    lines: list[str] = []
    imports: set[str] = set()
    warnings: list[str] = []
    outputs: dict[str, str] = {}
    for step in body.topological_order():
        if isinstance(step, CommentNode):
            lines += [f"# {line}" for line in (step.comment_text or "").splitlines()]
            continue
        if isinstance(step, MacroIONode):
            if step.direction == "input":
                var_map[step.node_id] = {"Output": f"df_{step.node_id}"}
            else:
                inputs = gen._resolve_input_vars(step.node_id, body, var_map)
                outputs[step.field_name] = next(iter(inputs.values()), "None")
            continue
        inputs = gen._resolve_input_vars(step.node_id, body, var_map)
        result = gen._generate_node_code(step, inputs, dag=body)
        var_map[step.node_id] = result.output_vars
        imports.update(result.imports)
        warnings.extend(_readable(w, node.macro_name) for w in result.warnings)
        # Not "# Step N:": that's the notebook's own cell header.
        lines.append(f"# macro tool {step.node_id % _BAND}: {step.original_tool_type or type(step).__name__}")
        lines += result.code_lines
    return lines, imports, warnings, outputs


def _readable(warning: str, macro: str) -> str:
    """``node 1000003`` -> ``tool 3 in <macro>`` (tool ids inside a macro are banded)."""
    return re.sub(r"\bnode (\d{7,})\b", lambda m: f"tool {int(m.group(1)) % _BAND} in {macro}", warning)


def _union(var: str, parts: str, by_position: bool) -> list[str]:
    """``var`` = the union of the DataFrames in the list ``parts`` (no columns when there are none)."""
    join = "a.union(b)" if by_position else "a.unionByName(b, allowMissingColumns=True)"
    return [f"{var} = functools.reduce(lambda a, b: {join}, {parts}) if {parts} else spark.range(0).drop('id')"]


def looping_macro_lines(gen: PySparkGenerator, node: LoopingMacroNode, input_vars: dict[str, str]) -> NodeCodeResult:
    lines_in, imports, warnings, outputs = _body(gen, node)
    fn = node.function_name
    nid = node.node_id
    params = {int(SENTINEL_RE.fullmatch(p.sentinel).group(1)): p.var for p in node.params}  # type: ignore[union-attr]
    iteration = _ITERATION_VAR if node.uses_iteration_number else None
    args = (
        [f"df_{bid}" for _, bid in node.inputs] + [p.var for p in node.params] + ([_ITERATION_VAR] if iteration else [])
    )
    ret = ", ".join(f"{name!r}: {outputs.get(name, 'None')}" for name, _ in node.outputs)
    source = "\n".join([f"def {fn}({', '.join(args)}):", _indent("\n".join(lines_in)), f"    return {{{ret}}}"])
    suffixes = {n: p.suffix for n, p in zip(params, node.params, strict=True) if p.suffix}
    source, left = substitute(source, params, iteration, suffixes)
    issues = list(node.issues)
    if left:
        issues.append("a control value couldn't be wired into: " + ", ".join(sorted(set(left)))[:300])

    out_vars = output_vars(node)
    by_position = "position" in node.output_mode.lower()
    control = input_vars.get("Control")
    what = "batch" if node.kind == "batch" else "iterative"
    head = [
        f"# {what.capitalize()} macro {node.macro_name}: "
        + (
            "Alteryx runs it once per control record and unions the runs."
            if node.kind == "batch"
            else "Alteryx re-runs it on its iteration output until that's empty."
        ),
        *(f"# TODO: {issue}" for issue in issues),
        source,
        "",
    ]

    def call(inputs: dict[str, str], extra: list[str]) -> str:
        actual = [inputs.get(name, "None") for name, _ in node.inputs]
        return f"{fn}({', '.join(actual + extra)})"

    if node.kind == "batch":
        text = "_text = lambda v: '' if v is None else str(v)  # Alteryx passes control values as text"
        run_inputs = dict(input_vars)
        for control_field, anchor, input_field in node.group_by:
            if anchor in run_inputs:
                cond = f"F.col({input_field!r}).eqNullSafe(F.lit(_row[{control_field!r}]))"
                run_inputs[anchor] = f"{run_inputs[anchor]}.filter({cond})"
        extra = [f"{p.var}=_text(_row[{p.control_field!r}])" for p in node.params]
        if iteration:
            extra.append(f"{_ITERATION_VAR}=_i")
        loop = [
            text,
            f"_runs_{nid} = [",
            f"    {call(run_inputs, extra)}",
            f"    for _i, _row in enumerate({control or 'None'}.collect())  # one run per control record",
            "]",
        ]
        assign: list[str] = []
        for name, var in out_vars.items():
            parts = f"_parts_{nid}_{_slug(name)}"
            assign += [f"{parts} = [_r[{name!r}] for _r in _runs_{nid}]", *_union(var, parts, by_position)]
        code = [*head, *loop, *assign]
    else:
        it_in, it_out = node.iteration_input, node.iteration_output
        feed = f"_df_{nid}_iter"
        run_inputs = {**input_vars, it_in: feed}
        others = [name for name, _ in node.outputs if name != it_out]
        limit = node.iteration_limit
        on_limit = {
            "Error": f"    raise RuntimeError('Iterative macro {node.macro_name} hit its limit of {limit} iterations')",
            "Warn": f"    print('WARNING: iterative macro {node.macro_name} stopped at its limit of {limit} iterations')",
        }.get(node.limit_behavior, f"    pass  # at the limit, what's left goes out on {it_out}")
        code = [
            *head,
            f"{feed} = {input_vars.get(it_in, 'None')}",
            f"_parts_{nid} = {{{', '.join(f'{n!r}: []' for n in others)}}}",
            f"for {_ITERATION_VAR} in range({limit}):",
            f"    _out = {call(run_inputs, [_ITERATION_VAR] if iteration else [])}",
            *(f"    _parts_{nid}[{n!r}].append(_out[{n!r}])" for n in others),
            f"    {feed} = _out[{it_out!r}].localCheckpoint()  # cut the plan so it doesn't grow each pass",
            f"    if {feed}.isEmpty():",
            "        break",
            "else:",
            on_limit,
            *(line for n in others for line in _union(out_vars[n], f"_parts_{nid}[{n!r}]", by_position)),
            *([f"{out_vars[it_out]} = {feed}  # empty unless the limit was hit"] if it_out in out_vars else []),
        ]
    imports.add("import functools")
    return NodeCodeResult(code_lines=code, output_vars=out_vars, imports=imports, warnings=warnings)
